const STORAGE_COST: u128 = JOB_STORAGE_DEPOSIT_INITIAL;

fn acc(s: &str) -> AccountId {
    s.parse().unwrap()
}
fn h(b: u8) -> Hex32 {
    let mut arr = [0u8; 32];
    arr[0] = b;
    Hex32(arr)
}
fn usdc(n: u128) -> u128 {
    n * 1_000_000
}

// Decision 2: job ids are generated by the contract. Tests keep readable numeric tags and map each tag to the
// id the contract actually issued (per test thread).
thread_local! {
    static JOB_IDS: RefCell<HashMap<u8, Hex32>> = RefCell::new(HashMap::new());
}
fn reg(tag: u8, id: Hex32) -> Hex32 {
    JOB_IDS.with(|m| m.borrow_mut().insert(tag, id));
    id
}
fn j(tag: u8) -> Hex32 {
    JOB_IDS.with(|m| *m.borrow().get(&tag).unwrap_or_else(|| panic!("job tag {tag} was never created")))
}
#[allow(clippy::too_many_arguments)]
fn create_job_t(
    c: &mut Contract,
    tag: u8,
    customer: AccountId,
    operator: AccountId,
    pay: U128,
    budget: U128,
    terms: Hex32,
    deadline: u64,
) -> Hex32 {
    let id = c.create_job(customer, operator, pay, budget, terms, deadline);
    reg(tag, id)
}

fn ctx(predecessor: &str, deposit: u128, ts_sec: u64, block: u64, pr: Vec<PromiseResult>) {
    let mut b = VMContextBuilder::new();
    b.current_account_id(acc("core.snapfall.testnet"))
        .predecessor_account_id(acc(predecessor))
        .signer_account_id(acc(predecessor))
        .attached_deposit(NearToken::from_yoctonear(deposit))
        .prepaid_gas(Gas::from_tgas(200))
        .block_timestamp(ts_sec * 1_000_000_000)
        .block_height(block);
    let context = b.build();
    testing_env!(
        context,
        near_sdk::test_vm_config(),
        near_sdk::RuntimeFeesConfig::test(),
        Default::default(),
        pr
    );
}

fn setup_core() -> Contract {
    ctx("admin.testnet", 0, 1_000, 1, vec![]);
    let mut c = Contract::new(acc("usdc.testnet"), acc("admin.testnet"));
    ctx("admin.testnet", 1, 1_000, 1, vec![]);
    c.set_max_job_payment(U128(usdc(1_000)));
    c.set_caps(U128(usdc(10_000)), U128(usdc(500)));
    c
}

/// Deposit `amount` of storage credit for `who`; the first deposit also pays the record registration (Decision 4).
fn fund_storage(c: &mut Contract, who: &str, amount: u128) {
    let reg_fee = if c.storage_registration_of(acc(who)).0 == 0 { STORAGE_REGISTRATION } else { 0 };
    ctx(who, amount + reg_fee, 1_000, 1, vec![]);
    c.storage_deposit(None);
}

fn seed_pool(c: &mut Contract, amount: u128) {
    // Decision 3: the LP funds its share entry (all exit storage reserved up front) from storage credits.
    fund_storage(c, "admin.testnet", LP_SHARE_STAKE);
    ctx("usdc.testnet", 0, 1_000, 1, vec![]);
    let _ = c.ft_on_transfer(
        acc("admin.testnet"),
        U128(amount),
        r#"{"DepositPool":{"receiver":null}}"#.to_string(),
    );
}

fn create_and_fund_for(c: &mut Contract, job: u8, customer: &str, operator: &str, pay: u128, deadline: u64) {
    fund_storage(c, customer, STORAGE_COST);
    let expected = crate::derive_job_id(&acc(customer), c.next_job_seq());
    ctx("usdc.testnet", 0, 1_000, 1, vec![]);
    let msg = serde_json::json!({
        "CreateAndFundJob": {
            "operator": operator,
            "max_operating_budget": U128(pay / 2),
            "terms_hash": h(0xaa),
            "deadline": deadline
        }
    })
    .to_string();
    let _ = c.ft_on_transfer(acc(customer), U128(pay), msg);
    assert!(c.get_job(expected).is_some(), "CreateAndFundJob did not create the derived id");
    reg(job, expected);
}

fn create_and_fund(c: &mut Contract, job: u8, pay: u128, deadline: u64) {
    create_and_fund_for(c, job, "customer.testnet", "operator.testnet", pay, deadline);
}
fn resolve_ok(c: &mut Contract, op_id: u64, block: u64) {
    ctx(
        "core.snapfall.testnet",
        0,
        1_001,
        block,
        vec![PromiseResult::Successful(vec![])],
    );
    c.on_payout_complete(op_id);
}

