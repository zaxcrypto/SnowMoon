//! JobVault module (escrow lifecycle, authorization, and audit verification view).
use crate::events::{self, JsonObj};
use crate::types::{
    AdvanceStatus, AuditJobVerification, Hex32, Job, JobStatus, JobView, PendingOpKind,
};
use crate::{block_timestamp_sec, Contract, ContractExt, MIN_PREPAID_GAS_PAYOUT};
use near_sdk::json_types::U128;
use near_sdk::{env, near, require, AccountId, Promise, PromiseOrValue};

impl Contract {
    fn no_payout_pending_advance(&self, job_id: &Hex32) -> bool {
        self.advances
            .get(job_id)
            .map(|a| a.status != AdvanceStatus::PayoutPending)
            .unwrap_or(true)
    }

    pub(crate) fn handle_create_and_fund(
        &mut self,
        sender_id: AccountId,
        amount: u128,
        supplied_job_id: Option<Hex32>,
        operator: AccountId,
        max_operating_budget: u128,
        terms_hash: Hex32,
        deadline: u64,
    ) -> PromiseOrValue<U128> {
        require!(!self.vault_paused, "ERR_VAULT_PAUSED");
        require!(supplied_job_id.is_none(), "ERR_JOB_ID_IS_CONTRACT_GENERATED");
        require!(self.max_job_payment > 0, "ERR_CAP_NOT_SET");
        require!(amount > 0, "ERR_ZERO_AMOUNT");
        require!(amount <= self.max_job_payment, "ERR_JOB_TOO_LARGE");

        // POD-03A: sender_id is fixed as customer, storage sponsor and (Decision 2) id creator.
        let locked = self.lock_storage_from_credits(&sender_id);
        let (job_id, seq) = self.issue_job_id(&sender_id);
        let job = Job {
            customer: sender_id.clone(),
            operator: operator.clone(),
            customer_payment: amount,
            max_operating_budget,
            onchain_expenses: 0,
            terms_hash,
            delivery_hash: Hex32::ZERO,
            deadline,
            status: JobStatus::Funded,
            storage_sponsor: sender_id.clone(),
            storage_locked: locked,
            active_op_id: None,
        };
        self.jobs.insert(job_id, job);
        self.escrowed_usdc = self
            .escrowed_usdc
            .checked_add(amount)
            .expect("ERR_ESCROW_OVERFLOW");

        events::simple(
            "JobCreated",
            JsonObj::new()
                .hex("jobId", &job_id)
                .acc("creator", &sender_id)
                .u64_num("seq", seq)
                .acc("customer", &sender_id)
                .acc("operator", &operator)
                .u128_str("customerPaymentAtomic", amount)
                .u128_str("maxOperatingBudgetAtomic", max_operating_budget)
                .hex("termsHash", &terms_hash)
                .u64_num("deadline", deadline),
        );
        events::job_funded(&job_id, amount);
        PromiseOrValue::Value(U128(0))
    }

    pub(crate) fn handle_fund_job(
        &mut self,
        sender_id: AccountId,
        amount: u128,
        job_id: Hex32,
    ) -> PromiseOrValue<U128> {
        require!(!self.vault_paused, "ERR_VAULT_PAUSED");
        let job = self.jobs.get_mut(&job_id).expect("ERR_UNKNOWN_JOB");
        require!(
            sender_id == job.customer || self.allowed_relayers.contains(&sender_id),
            "ERR_NOT_AUTHORIZED"
        );
        require!(job.status == JobStatus::Created, "ERR_INVALID_STATUS");
        require!(amount == job.customer_payment, "ERR_WRONG_FUNDING_AMOUNT");

        job.status = JobStatus::Funded;
        self.escrowed_usdc = self
            .escrowed_usdc
            .checked_add(amount)
            .expect("ERR_ESCROW_OVERFLOW");
        events::job_funded(&job_id, amount);
        PromiseOrValue::Value(U128(0))
    }
}

#[near]
impl Contract {
    /// Decision 2: the job id is generated by the contract and returned (also emitted in `JobCreated`).
    #[payable]
    pub fn create_job(
        &mut self,
        customer: AccountId,
        operator: AccountId,
        customer_payment: U128,
        max_operating_budget: U128,
        terms_hash: Hex32,
        deadline: u64,
    ) -> Hex32 {
        require!(!self.vault_paused, "ERR_VAULT_PAUSED");
        let caller = env::predecessor_account_id();
        require!(
            caller == self.admin || caller == operator,
            "ERR_NOT_AUTHORIZED"
        );
        require!(self.max_job_payment > 0, "ERR_CAP_NOT_SET");
        require!(customer_payment.0 > 0, "ERR_ZERO_AMOUNT");
        require!(customer_payment.0 <= self.max_job_payment, "ERR_JOB_TOO_LARGE");

        let locked = self.lock_storage_for_create_job(&caller);
        let (job_id, seq) = self.issue_job_id(&caller);
        let job = Job {
            customer: customer.clone(),
            operator: operator.clone(),
            customer_payment: customer_payment.0,
            max_operating_budget: max_operating_budget.0,
            onchain_expenses: 0,
            terms_hash,
            delivery_hash: Hex32::ZERO,
            deadline,
            status: JobStatus::Created,
            storage_sponsor: caller.clone(),
            storage_locked: locked,
            active_op_id: None,
        };
        self.jobs.insert(job_id, job);

        events::simple(
            "JobCreated",
            JsonObj::new()
                .hex("jobId", &job_id)
                .acc("creator", &caller)
                .u64_num("seq", seq)
                .acc("customer", &customer)
                .acc("operator", &operator)
                .u128_str("customerPaymentAtomic", customer_payment.0)
                .u128_str("maxOperatingBudgetAtomic", max_operating_budget.0)
                .hex("termsHash", &terms_hash)
                .u64_num("deadline", deadline),
        );
        job_id
    }

    pub fn start_work(&mut self, job_id: Hex32) {
        require!(self.no_payout_pending_advance(&job_id), "ERR_ADVANCE_PAYOUT_PENDING");
        let job = self.jobs.get_mut(&job_id).expect("ERR_UNKNOWN_JOB");
        require!(env::predecessor_account_id() == job.operator, "ERR_NOT_OPERATOR");
        require!(job.status == JobStatus::Funded, "ERR_INVALID_STATUS");
        job.status = JobStatus::InProgress;
        events::simple("WorkStarted", JsonObj::new().hex("jobId", &job_id));
    }

    pub fn record_expense(&mut self, job_id: Hex32, amount: U128, receipt_hash: Hex32) {
        let job = self.jobs.get_mut(&job_id).expect("ERR_UNKNOWN_JOB");
        require!(env::predecessor_account_id() == job.operator, "ERR_NOT_OPERATOR");
        require!(job.status == JobStatus::InProgress, "ERR_INVALID_STATUS");
        require!(amount.0 > 0, "ERR_ZERO_AMOUNT");
        let spent = job
            .onchain_expenses
            .checked_add(amount.0)
            .expect("ERR_OVER_BUDGET");
        require!(spent <= job.max_operating_budget, "ERR_OVER_BUDGET");
        job.onchain_expenses = spent;
        events::expense_recorded(&job_id, amount.0, &receipt_hash);
    }

    pub fn submit_delivery(&mut self, job_id: Hex32, delivery_hash: Hex32) {
        let job = self.jobs.get_mut(&job_id).expect("ERR_UNKNOWN_JOB");
        require!(env::predecessor_account_id() == job.operator, "ERR_NOT_OPERATOR");
        require!(job.status == JobStatus::InProgress, "ERR_INVALID_STATUS");
        require!(!delivery_hash.is_zero(), "ERR_ZERO_HASH");
        job.delivery_hash = delivery_hash;
        job.status = JobStatus::Delivered;
        events::delivery_submitted(&job_id, &delivery_hash);
    }

    /// Customer-only acceptance. Pool repaid synchronously BEFORE operator payout Promise is spawned. Never paused.
    #[payable]
    pub fn accept_delivery(&mut self, job_id: Hex32) -> Promise {
        require!(env::attached_deposit().as_yoctonear() <= 1, "ERR_EXCESS_DEPOSIT");
        require!(env::prepaid_gas() >= MIN_PREPAID_GAS_PAYOUT, "ERR_INSUFFICIENT_GAS");
        require!(self.no_payout_pending_advance(&job_id), "ERR_ADVANCE_PAYOUT_PENDING");

        let caller = env::predecessor_account_id();
        let (customer, operator, payment, status) = {
            let j = self.jobs.get(&job_id).expect("ERR_UNKNOWN_JOB");
            (j.customer.clone(), j.operator.clone(), j.customer_payment, j.status)
        };
        require!(caller == customer, "ERR_NOT_CUSTOMER");
        require!(status == JobStatus::Delivered, "ERR_INVALID_STATUS");

        // Synchronous waterfall step 1: repay pool first.
        let advance_repaid = self.repay_advance_internal(&job_id);
        let operator_net = payment
            .checked_sub(advance_repaid)
            .expect("ERR_ESCROW_UNDERFLOW");
        require!(operator_net > 0, "ERR_ZERO_OPERATOR_NET");

        self.escrowed_usdc -= payment;
        let (op_id, promise) = self.spawn_usdc_payout(
            PendingOpKind::SettlementOperatorPayout {
                job_id,
                advance_repaid,
            },
            operator,
            operator_net,
        );

        let job = self.jobs.get_mut(&job_id).unwrap();
        job.status = JobStatus::Settling;
        job.active_op_id = Some(op_id);
        promise
    }

    /// Customer-first refund: full customer_payment queued to customer, and open advance written off synchronously. Never paused.
    #[payable]
    pub fn refund(&mut self, job_id: Hex32) -> Promise {
        require!(env::attached_deposit().as_yoctonear() <= 1, "ERR_EXCESS_DEPOSIT");
        require!(env::prepaid_gas() >= MIN_PREPAID_GAS_PAYOUT, "ERR_INSUFFICIENT_GAS");
        require!(self.no_payout_pending_advance(&job_id), "ERR_ADVANCE_PAYOUT_PENDING");

        let caller = env::predecessor_account_id();
        let (customer, operator, payment, deadline, status) = {
            let j = self.jobs.get(&job_id).expect("ERR_UNKNOWN_JOB");
            (
                j.customer.clone(),
                j.operator.clone(),
                j.customer_payment,
                j.deadline,
                j.status,
            )
        };
        let privileged = caller == operator || caller == self.admin;
        let customer_after_deadline = caller == customer && block_timestamp_sec() >= deadline;
        require!(privileged || customer_after_deadline, "ERR_NOT_AUTHORIZED");
        require!(
            matches!(status, JobStatus::Funded | JobStatus::InProgress | JobStatus::Delivered),
            "ERR_INVALID_STATUS"
        );

        // Write off any open advance synchronously first (pool losses do not reduce customer restitution).
        self.write_off_internal(&job_id);

        self.escrowed_usdc -= payment;
        let (op_id, promise) =
            self.spawn_usdc_payout(PendingOpKind::RefundCustomer { job_id }, customer, payment);

        let job = self.jobs.get_mut(&job_id).unwrap();
        job.status = JobStatus::Refunding;
        job.active_op_id = Some(op_id);
        promise
    }

    /// Cancel an unfunded Created job. Never paused.
    /// Decision 2: the full `Job` record is deleted and the exact `storage_locked` is credited back to
    /// `storage_credits[storage_sponsor]`. Non-reuse needs no tombstone: ids are contract-derived from a
    /// strictly increasing sequence, and no entry point accepts a caller-chosen id for job creation.
    pub fn cancel(&mut self, job_id: Hex32) {
        let caller = env::predecessor_account_id();
        let (sponsor, locked) = {
            let job = self.jobs.get(&job_id).expect("ERR_UNKNOWN_JOB");
            require!(
                caller == job.customer || caller == job.operator || caller == self.admin,
                "ERR_NOT_AUTHORIZED"
            );
            require!(job.status == JobStatus::Created, "ERR_INVALID_STATUS");
            (job.storage_sponsor.clone(), job.storage_locked)
        };
        self.jobs.remove(&job_id);
        self.release_locked_storage(&sponsor, locked);
        events::simple(
            "JobCancelled",
            JsonObj::new()
                .hex("jobId", &job_id)
                .u128_str("storageRefundedYocto", locked)
                .acc("storageRefundedTo", &sponsor),
        );
    }

    /// Next sequence number the contract will use (ids are issued strictly in increasing order).
    pub fn next_job_seq(&self) -> u64 {
        self.next_job_seq
    }

    /// Pure helper so clients can recompute an issued id from `(creator, seq)` found in `JobCreated`.
    pub fn derive_job_id(&self, creator: AccountId, seq: u64) -> Hex32 {
        crate::derive_job_id(&creator, seq)
    }

    pub fn get_job(&self, job_id: Hex32) -> Option<JobView> {
        self.jobs.get(&job_id).map(|j| JobView {
            job_id,
            customer: j.customer.clone(),
            operator: j.operator.clone(),
            customer_payment: U128(j.customer_payment),
            max_operating_budget: U128(j.max_operating_budget),
            onchain_expenses: U128(j.onchain_expenses),
            terms_hash: j.terms_hash,
            delivery_hash: j.delivery_hash,
            deadline: j.deadline,
            status: j.status,
            storage_sponsor: j.storage_sponsor.clone(),
            storage_locked: U128(j.storage_locked),
            active_op_id: j.active_op_id,
        })
    }

    /// Dedicated minimal cross-contract verification interface for `snapfall-audit` (MC-02).
    pub fn verify_job_for_audit(&self, job_id: Hex32) -> AuditJobVerification {
        match self.jobs.get(&job_id) {
            Some(job) => AuditJobVerification {
                exists: true,
                status: Some(job.status),
                delivery_hash: Some(job.delivery_hash),
            },
            None => AuditJobVerification {
                exists: false,
                status: None,
                delivery_hash: None,
            },
        }
    }
}

