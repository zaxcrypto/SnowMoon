// T-02: [CRIT-02] Auth - CreateAndFundJob binds sender_id as customer
#[test]
fn test_create_and_fund_binds_sender_as_customer() {
    let mut c = setup_core();
    create_and_fund(&mut c, 2, usdc(25), 5_000);
    assert_eq!(c.get_job(j(2)).unwrap().customer, acc("customer.testnet"));

    // Even if an attacker injects an extra `"customer": "victim.testnet"` field in JSON,
    // CreateAndFundJob binds `job.customer = sender_id` ("customer.testnet").
    fund_storage(&mut c, "customer.testnet", STORAGE_COST);
    reg(3, crate::derive_job_id(&acc("customer.testnet"), c.next_job_seq()));
    ctx("usdc.testnet", 0, 1_000, 1, vec![]);
    let injected = serde_json::json!({
        "CreateAndFundJob": {
            "operator": "operator.testnet",
            "customer": "victim.testnet",
            "max_operating_budget": U128(usdc(10)),
            "terms_hash": h(1),
            "deadline": 5_000
        }
    })
    .to_string();
    let _ = c.ft_on_transfer(acc("customer.testnet"), U128(usdc(25)), injected);
    assert_eq!(c.get_job(j(3)).unwrap().customer, acc("customer.testnet"));
}

// T-03: [HIGH-01] Auth - FundJob only customer or allowlisted relayer
#[test]
fn test_fund_job_only_customer_or_allowlisted_relayer() {
    let mut c = setup_core();
    ctx("operator.testnet", STORAGE_COST, 1_000, 1, vec![]);
    create_job_t(&mut c, 3,
        acc("customer.testnet"),
        acc("operator.testnet"),
        U128(usdc(25)),
        U128(usdc(10)),
        h(1),
        5_000,
    );

    // Stranger rejected
    ctx("usdc.testnet", 0, 1_001, 2, vec![]);
    let msg = serde_json::json!({"FundJob": {"job_id": j(3)}}).to_string();
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.ft_on_transfer(acc("stranger.testnet"), U128(usdc(25)), msg.clone());
    }))
    .is_err());

    // Operator (not customer, not relayer) also rejected
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.ft_on_transfer(acc("operator.testnet"), U128(usdc(25)), msg.clone());
    }))
    .is_err());

    // Relayer allowlist works and preserves job.customer
    ctx("admin.testnet", 1, 1_001, 2, vec![]);
    c.set_relayer_allowed(acc("intents-relayer.testnet"), true);
    ctx("usdc.testnet", 0, 1_002, 3, vec![]);
    let _ = c.ft_on_transfer(acc("intents-relayer.testnet"), U128(usdc(25)), msg);
    let jv = c.get_job(j(3)).unwrap();
    assert_eq!(jv.status, JobStatus::Funded);
    assert_eq!(jv.customer, acc("customer.testnet"));

    // Direct customer funding also succeeds
    ctx("operator.testnet", STORAGE_COST, 1_003, 4, vec![]);
    create_job_t(&mut c, 30,
        acc("customer.testnet"),
        acc("operator.testnet"),
        U128(usdc(25)),
        U128(usdc(10)),
        h(1),
        5_000,
    );
    ctx("usdc.testnet", 0, 1_004, 5, vec![]);
    let msg30 = serde_json::json!({"FundJob": {"job_id": j(30)}}).to_string();
    let _ = c.ft_on_transfer(acc("customer.testnet"), U128(usdc(25)), msg30);
    assert_eq!(c.get_job(j(30)).unwrap().status, JobStatus::Funded);
}

