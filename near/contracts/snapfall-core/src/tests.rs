    // 5. On a second job (h(201)) with 64-char accounts, measure request_advance (Advance record) + accept_delivery (OrgCredit record)
    ctx_keep_storage(&long_op, STORAGE_COST, 1_004, 5, vec![]);
    create_job_t(&mut c, 201,
        acc(&long_cust),
        acc(&long_op),
        U128(usdc(25)),
        U128(usdc(12)),
        h(0xaa),
        9_999_999_999,
    );
    ctx_keep_storage("usdc.testnet", 0, 1_004, 5, vec![]);
    let msg291 = serde_json::json!({"FundJob": {"job_id": j(201)}}).to_string();
