    let _ = c.claim_usdc(Some(U128(1)), None);
    ctx_keep_storage(&peak_cust, 1, 1_013, 25, vec![]);
    let _ = c.claim_usdc(Some(U128(1)), None);
    let u_peak1 = flush_contract_storage(&mut c);
    let worst_persistent = u_persist - u_peak0;
    let worst_peak = u_peak1 - u_peak0;
    assert_eq!(worst_persistent, 1_051); // 415 + 217 + 133 + 143 + 143
    assert_eq!(worst_peak, 1_521); // 415 + 217 + 133 + 151 + 151 + 227 + 227
    let required_peak_rounded = required(worst_peak);
    assert_eq!(required_peak_rounded, 23_000_000_000_000_000_000_000u128); // ceil(1.5 x 1,521)=2,282 B -> 0.023 NEAR

    println!(
        "STORAGE_DELTAS: storage_deposit={delta_storage_deposit}B, create_job={delta_create_job}B, create_and_fund={delta_create_and_fund}B, fund_job={delta_fund_job}B, delivery={delta_delivery}B, advance_inflight={delta_advance_inflight}B, advance_persisted={delta_advance_persisted}B, org_credit={delta_org_credit}B, job_with_delivery={job_bytes}B, total_lifecycle={total_lifecycle_bytes}B, worst_persistent={worst_persistent}B, worst_peak={worst_peak}B, required_job={required_job_rounded}, required_full={required_full_rounded}, required_peak={required_peak_rounded}"
    );

    // FC-04 gate: the configured deposit (no admin adjustment) must cover the worst-case peak at 1.5x.
