// Decision 4 (AUD-07): one in-flight claim per owner; additive restore; lock clears only on its own op;
// no duplicate payouts; successful, failed, concurrent and repeated claims.
#[test]
fn test_single_inflight_claim_per_owner() {
    let mut c = setup_core();
    seed_pool(&mut c, usdc(1_000));
    create_and_fund(&mut c, 70, usdc(20), 5_000);
    create_and_fund(&mut c, 71, usdc(10), 5_000);
    for id in [70u8, 71] {
        ctx("operator.testnet", 0, 1_001, 2, vec![]);
        c.start_work(j(id));
        c.submit_delivery(j(id), h(0x70));
    }
    let op = || acc("operator.testnet");
    let fail = |c: &mut Contract, id: u64| {
        ctx("core.snapfall.testnet", 0, 1_010, 10, vec![PromiseResult::Failed]);
        c.on_payout_complete(id);
    };

    ctx("customer.testnet", 0, 1_002, 3, vec![]);
    let _ = c.accept_delivery(j(70)); // op 1
    fail(&mut c, 1);
    assert_eq!(c.claimable_of(op()).0, usdc(20));

    // Partial claim (no minimum) -> op 2; lock set; remainder stays claimable
    ctx("operator.testnet", 1, 1_003, 4, vec![]);
    let _ = c.claim_usdc(Some(U128(usdc(5))), None);
    assert_eq!(c.claim_in_flight_of(op()), Some(2));
    assert_eq!(c.claimable_of(op()).0, usdc(15));

    // Concurrent second claim rejected; balance untouched
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.claim_usdc(Some(U128(1)), None);
    }))
    .is_err());
    assert_eq!(c.claimable_of(op()).0, usdc(15));

    // A different op failing for the same owner credits additively and does NOT clear the lock
    ctx("customer.testnet", 0, 1_004, 5, vec![]);
    let _ = c.accept_delivery(j(71)); // op 3
    fail(&mut c, 3);
    assert_eq!(c.claimable_of(op()).0, usdc(25));
    assert_eq!(c.claim_in_flight_of(op()), Some(2));

    // Claim op 2 succeeds -> lock cleared, nothing re-credited
    resolve_ok(&mut c, 2, 11);
    assert_eq!(c.claim_in_flight_of(op()), None);
    assert_eq!(c.claimable_of(op()).0, usdc(25));
    assert_eq!(c.accounting().total_claimable_usdc.0, usdc(25));

    // Repeated: full claim (op 4) fails -> full additive restore, lock cleared
    ctx("operator.testnet", 1, 1_005, 12, vec![]);
    let _ = c.claim_usdc(None, Some(acc("unregistered.testnet")));
    assert_eq!(c.claimable_of(op()).0, 0);
    assert_eq!(c.claim_in_flight_of(op()), Some(4));
    fail(&mut c, 4);
    assert_eq!(c.claimable_of(op()).0, usdc(25));
    assert_eq!(c.claim_in_flight_of(op()), None);

    // Full claim (op 5) succeeds -> entry removed
    ctx("operator.testnet", 1, 1_006, 13, vec![]);
    let _ = c.claim_usdc(None, None);
    resolve_ok(&mut c, 5, 14);
    assert_eq!(c.claimable_of(op()).0, 0);
    assert_eq!(c.claim_in_flight_of(op()), None);
    assert!(c.claimable_usdc.get(&op()).is_none());

    // No duplicate payout: a replayed callback for a resolved op is an anomaly with no effect
    let before = c.accounting();
    resolve_ok(&mut c, 5, 15);
    let after = c.accounting();
    assert_eq!(before.total_claimable_usdc, after.total_claimable_usdc);
    assert_eq!(before.total_in_flight_usdc, after.total_in_flight_usdc);
    assert_eq!(after.total_in_flight_usdc.0, 0);
    assert_eq!(after.total_claimable_usdc.0, 0);
}

// Decision 3: LP storage is caller-funded and reserved entirely at deposit time. Withdrawal never needs extra
// NEAR and is never paused; failed payouts are funded by pre-reserved slots whose stake returns to exactly the
// payer; all refunds are exact.
#[test]
fn test_lp_storage_is_caller_funded_with_exact_refunds() {
    let mut c = setup_core();
    ctx("admin.testnet", 1, 1_000, 1, vec![]);
    c.set_deposit_allowlist_enabled(false);
    let lp = || acc("lp.testnet");
    let deposit_msg = r#"{"DepositPool":{"receiver":null}}"#.to_string();
    let fail = |c: &mut Contract, id: u64| {
        ctx("core.snapfall.testnet", 0, 1_010, 10, vec![PromiseResult::Failed]);
        c.on_payout_complete(id);
    };

    // No storage credit -> DepositPool panics (token refunds the USDC); nothing written
    ctx("usdc.testnet", 0, 1_000, 1, vec![]);
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.ft_on_transfer(lp(), U128(usdc(100)), deposit_msg.clone());
    }))
    .is_err());
    assert_eq!(c.accounting().total_shares.0, 0);

    // Fund exactly the stake and deposit: the whole exit storage is reserved now
    fund_storage(&mut c, "lp.testnet", LP_SHARE_STAKE);
    ctx("usdc.testnet", 0, 1_001, 2, vec![]);
    let _ = c.ft_on_transfer(lp(), U128(usdc(100)), deposit_msg.clone());
    assert_eq!(c.storage_credit_of(lp()).0, 0);
    assert_eq!(c.share_storage_stake_of(lp()).0, LP_SHARE_STAKE);
    assert_eq!(c.accounting().total_storage_locked.0, LP_SHARE_STAKE);
    let _ = c.ft_on_transfer(lp(), U128(usdc(10)), deposit_msg.clone()); // existing entry: no charge
    assert_eq!(c.accounting().total_storage_locked.0, LP_SHARE_STAKE);

    // Exit #1 to self with ZERO storage credit (only the mandatory 1 yocto attached)
    ctx("lp.testnet", 1, 1_002, 3, vec![]);
    let _ = c.withdraw(U128(usdc(10)), None); // op 1
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.withdraw(U128(usdc(1)), None);
    }))
    .is_err(), "one exit in flight per LP");
    resolve_ok(&mut c, 1, 4);
    assert_eq!(c.share_storage_stake_of(lp()).0, LP_SHARE_STAKE);

    // Exit #2 to an external receiver fails -> receiver's claim entry funded by the external slot (payer = LP)
    ctx("lp.testnet", 1, 1_003, 5, vec![]);
    let _ = c.withdraw(U128(usdc(10)), Some(acc("rcv.testnet"))); // op 2
    fail(&mut c, 2);
    assert_eq!(c.claimable_of(acc("rcv.testnet")).0, usdc(10));
    let rcv_entry = c.claimable_usdc.get(&acc("rcv.testnet")).unwrap().clone();
    assert_eq!(rcv_entry.storage_stake, LP_CLAIM_SLOT_STAKE);
    assert_eq!(rcv_entry.storage_payer, Some((1, lp())));
    assert_eq!(c.share_storage_stake_of(lp()).0, LP_SHARE_STAKE - LP_CLAIM_SLOT_STAKE);
    assert_eq!(c.accounting().total_storage_locked.0, LP_SHARE_STAKE); // moved, not released

    // External slot busy -> another external exit is refused, but an exit to self is always available
    ctx("lp.testnet", 1, 1_004, 6, vec![]);
    assert!(std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let _ = c.withdraw(U128(usdc(1)), Some(acc("rcv2.testnet")));
    }))
    .is_err());
    let _ = c.withdraw(U128(usdc(10)), None); // op 3 (self)
    fail(&mut c, 3); // LP's own claim entry funded by the self slot
    assert_eq!(c.claimable_of(lp()).0, usdc(10));
    assert_eq!(c.share_storage_stake_of(lp()).0, LP_SHARE_BASE_STAKE);

    // Pause both circuit breakers: full exit still works, still with no extra NEAR
    ctx("admin.testnet", 1, 1_005, 7, vec![]);
    c.set_vault_paused(true);
    c.set_pool_paused(true);
    let shares = c.shares_of(lp());
    ctx("lp.testnet", 1, 1_005, 7, vec![]);
    let _ = c.redeem(shares, None); // op 4
    resolve_ok(&mut c, 4, 8);
    // Entry released: its remaining stake (base) refunded exactly to the LP's credits
    assert_eq!(c.shares_of(lp()).0, 0);
    assert_eq!(c.share_storage_stake_of(lp()).0, 0);
    assert_eq!(c.storage_credit_of(lp()).0, LP_SHARE_BASE_STAKE);
    assert_eq!(c.accounting().total_storage_locked.0, 2 * LP_CLAIM_SLOT_STAKE);

    // Receiver claims in full (while paused) -> its entry removed, slot stake returns to the PAYER (LP)
    ctx("rcv.testnet", 1, 1_006, 9, vec![]);
    let _ = c.claim_usdc(None, None); // op 5
    resolve_ok(&mut c, 5, 10);
    assert!(c.claimable_usdc.get(&acc("rcv.testnet")).is_none());
    assert_eq!(c.storage_credit_of(acc("rcv.testnet")).0, 0);
    assert_eq!(c.storage_credit_of(lp()).0, LP_SHARE_BASE_STAKE + LP_CLAIM_SLOT_STAKE);

    // LP claims its own balance -> self-slot stake returns to the LP
    ctx("lp.testnet", 1, 1_007, 11, vec![]);
    let _ = c.claim_usdc(None, None); // op 6
    resolve_ok(&mut c, 6, 12);
    assert_eq!(c.storage_credit_of(lp()).0, LP_SHARE_STAKE, "LP NEAR conserved exactly");
    assert_eq!(c.accounting().total_storage_locked.0, 0);

    // Full storage exit: balance withdrawn, then registration refunded and the record removed
    ctx("lp.testnet", 1, 1_008, 13, vec![]);
    let _ = c.storage_withdraw(None);
    ctx("core.snapfall.testnet", 0, 1_008, 14, vec![PromiseResult::Successful(vec![])]);
    c.on_storage_withdraw_complete(1);
    assert_eq!(c.storage_credit_of(lp()).0, 0);
    assert_eq!(c.storage_registration_of(lp()).0, 0);
    assert_eq!(c.accounting().total_storage_registration.0, 0);
    assert_eq!(c.accounting().total_storage_credits.0, 0);
}

