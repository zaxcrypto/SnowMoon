fn flush_contract_storage(c: &mut Contract) -> u64 {
    c.jobs.flush();
    c.advances.flush();
    c.org_credit.flush();
    c.shares_of.flush();
    c.claimable_usdc.flush();
    c.storage_credits.flush();
    c.pending_ops.flush();
    c.pending_near_ops.flush();
    c.storage_withdraw_lock.flush();
    near_sdk::env::state_write(c);
    near_sdk::env::storage_usage()
}

