    let _ = c.ft_on_transfer(acc(&peak_cust), U128(usdc(25)), serde_json::json!({"FundJob": {"job_id": pj}}).to_string());
    let op_adv = c.next_op_id;
    ctx_keep_storage(&peak_op, 0, 1_011, 21, vec![]);
    let _ = c.request_advance(pj, U128(12_500_000));
    ctx_keep_storage("core.snapfall.testnet", 0, 1_011, 22, vec![PromiseResult::Failed]);
    c.on_payout_complete(op_adv); // operator claim entry
    let op_ref = c.next_op_id;
    ctx_keep_storage(&peak_op, 0, 1_012, 23, vec![]);
    let _ = c.refund(pj);
    ctx_keep_storage("core.snapfall.testnet", 0, 1_012, 24, vec![PromiseResult::Failed]);
    c.on_payout_complete(op_ref); // customer claim entry
