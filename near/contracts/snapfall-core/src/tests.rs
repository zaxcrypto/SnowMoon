    // first-time operator. Every transfer fails, then BOTH the operator and the customer have a claim in flight:
    // Job 415 + Advance(WrittenOff) 217 + OrgCredit 133 + 2 x claim entry(active) 151 + 2 x Claim PendingOp 227.
