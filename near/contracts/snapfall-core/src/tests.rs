    let delta_org_credit = u_after_settle - u_after_deliv2;
    let total_lifecycle_bytes = delta_create_job + delta_delivery + delta_advance_persisted + delta_org_credit;

    // Also measure CreateAndFundJob path (consuming pre-deposited storage_credits)
    let long_cust2 = format!("{}.test.near", "d".repeat(54));
    ctx_keep_storage(&long_cust2, STORAGE_COST + STORAGE_REGISTRATION, 1_006, 9, vec![]);
    c.storage_deposit(None);
    let u6 = flush_contract_storage(&mut c);
    ctx_keep_storage("usdc.testnet", 0, 1_007, 10, vec![]);
    let msg_caf = serde_json::json!({
        "CreateAndFundJob": {
            "operator": &long_op,
            "max_operating_budget": U128(usdc(12)),
            "terms_hash": h(0xaa),
            "deadline": 9_999_999_999u64
        }
    })
    .to_string();
    let _ = c.ft_on_transfer(acc(&long_cust2), U128(usdc(25)), msg_caf);
    let u7 = flush_contract_storage(&mut c);
    let delta_create_and_fund = u7 - u6;

    // Storage byte cost on NEAR is 10^19 yoctoNEAR/byte (0.00001 NEAR/byte); every record also carries 40 B of
    // trie overhead (near-parameters storage_num_extra_bytes_record), which env::storage_usage() includes.
    // Exact byte verification against Borsh + NEAR 40B per-record trie overhead:
    // (Decision 4 changed two expected values: the storage-credit record now also stores its registration
    //  (+16 B) and is kept at zero balance, so CreateAndFundJob no longer deletes it.)
    assert_eq!(delta_storage_deposit, 141); // 40B trie + 69B key + 32B {balance, registration}
    assert_eq!(delta_create_job, 415); // 40B trie + 33B key + 342B Job
    assert_eq!(delta_create_and_fund, 415); // +415B Job; credit record retained at balance 0
    assert_eq!(delta_fund_job, 0);
    assert_eq!(delta_delivery, 0);
    assert_eq!(delta_advance_inflight, 549); // 225B Advance(Some) + 133B OrgCredit + 191B PendingOp
    assert_eq!(delta_advance_persisted, 350); // 217B Advance(None) + 133B OrgCredit
    assert_eq!(total_lifecycle_bytes, 765); // 415B Job + 217B Advance + 133B OrgCredit

    let byte_cost = 10_000_000_000_000_000_000u128;
    let milli_near = 1_000_000_000_000_000_000_000u128;
    // required = ceil(1.5 x bytes) x byte_cost, rounded up to the next 0.001 NEAR (FC-04 section 9.3 item 3)
    let required = |bytes: u64| {
        let y = ((bytes as u128 * 3 + 1) / 2) * byte_cost;
        ((y + milli_near - 1) / milli_near) * milli_near
    };
    let job_bytes = delta_create_job + delta_fund_job + delta_delivery;
    let required_job_rounded = required(job_bytes);
    let required_full_rounded = required(total_lifecycle_bytes);
    assert_eq!(required_job_rounded, 7_000_000_000_000_000_000_000u128); // 0.007 NEAR
    assert_eq!(required_full_rounded, 12_000_000_000_000_000_000_000u128); // 0.012 NEAR

